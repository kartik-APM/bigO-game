#!/usr/bin/env node
// Generates supabase/answers.sql from snippets/*/meta.json: an idempotent
// upsert of the answer key, plus removal of snippets that no longer exist.
// Run in the Supabase SQL Editor (or psql) after changing any meta.json.
//
//   node scripts/gen-answers-sql.mjs          write supabase/answers.sql
//   node scripts/gen-answers-sql.mjs --check  exit 1 if the file is out of date

import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const OUT = join(ROOT, 'supabase', 'answers.sql');

const lit = (s) => `'${String(s).replaceAll("'", "''")}'`;

export function buildAnswersSql(snippetsDir = join(ROOT, 'snippets')) {
  const ids = readdirSync(snippetsDir, { withFileTypes: true })
    .filter((d) => d.isDirectory())
    .map((d) => d.name)
    .sort();
  if (ids.length === 0) throw new Error('no snippets found');

  const rows = ids.map((id) => {
    const meta = JSON.parse(readFileSync(join(snippetsDir, id, 'meta.json'), 'utf8'));
    return `  (${lit(id)}, ${lit(meta.answer)}, ${lit(meta.title)}, ${lit(meta.why)})`;
  });

  return [
    '-- Generated by scripts/gen-answers-sql.mjs from snippets/*/meta.json. Do not edit by hand.',
    '-- Safe to run repeatedly. Removing a snippet that past runs used fails on purpose',
    '-- (foreign key from run_questions), so history is never orphaned.',
    '',
    'begin;',
    '',
    'insert into public.snippet_answers (snippet_id, answer, title, why) values',
    rows.join(',\n'),
    'on conflict (snippet_id) do update',
    '  set answer = excluded.answer, title = excluded.title, why = excluded.why, updated_at = now()',
    '  where (snippet_answers.answer, snippet_answers.title, snippet_answers.why)',
    '        is distinct from (excluded.answer, excluded.title, excluded.why);',
    '',
    'delete from public.snippet_answers where snippet_id <> all (array[',
    ids.map((id) => `  ${lit(id)}`).join(',\n'),
    ']::text[]);',
    '',
    'commit;',
    '',
  ].join('\n');
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const sql = buildAnswersSql();
  if (process.argv.includes('--check')) {
    const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
    if (current !== sql) {
      console.error('supabase/answers.sql is out of date. Run: npm run db:answers');
      process.exit(1);
    }
    console.log('supabase/answers.sql is up to date.');
  } else {
    writeFileSync(OUT, sql);
    console.log(`wrote ${OUT}`);
  }
}
